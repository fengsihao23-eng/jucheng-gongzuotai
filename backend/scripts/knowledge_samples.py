def build_docx(spec: dict) -> bytes:
    import io

    from docx import Document
    doc = Document()
    doc.add_heading(spec["title"], 0)
    for kind, val in spec["blocks"]:
        if kind == "h":
            doc.add_heading(val, 1)
        elif kind == "p":
            doc.add_paragraph(val)
        else:
            tb = doc.add_table(rows=0, cols=len(val[0]))
            tb.style = "Table Grid"
            for row in val:
                cells = tb.add_row().cells
                for i, v in enumerate(row):
                    cells[i].text = v
    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


def write_samples(directory: Path) -> dict[str, Path]:
    directory.mkdir(parents=True, exist_ok=True)
    out = {}
    for name, spec in ((TENDER_FILE, TENDER), (BID_FILE, BID), (MATERIAL_FILE, MATERIAL)):
        p = directory / name
        p.write_bytes(build_docx(spec))
        out[name] = p
    return out
