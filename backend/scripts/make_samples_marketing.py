FIELDS = ["contract_no", "project_code", "customer_name", "amount", "sign_date", "business_line", "owner"]


def make_contracts():
    wb = Workbook()
    ws = wb.active
    ws.title = "销售合同"
    ws.append(["2026 年度销售合同汇总表（各区域报送）"])
    ws.merge_cells("A1:J1")
    ws["A1"].font, ws["A1"].alignment = Font(bold=True, size=14), Alignment(horizontal="center")
    ws.append(["说明：数据来自各区域销售自报，格式未统一，导入前需清洗"])
    ws.append(["序号", "签约日期", "甲方", "编号", "类别", "含税金额", "所属项目", "经办人", "合同名称", "备注"])
    expected, n = [], 0
    for item in C:
        if item is None:
            ws.append([])
            continue
        cells, exp = item
        n += 1
        ws.append([n] + cells)
        r = ws.max_row
        if isinstance(cells[0], date):
            ws.cell(r, 2).number_format = "yyyy-mm-dd"
        e = {"seq": n, "source_row": r, "status": exp[0]}
        if exp[0] in ("ok", "fixed"):
            e["fields"] = dict(zip(FIELDS, exp[1:]))
        elif exp[0] == "error":
            e["issue_contains"] = exp[1]
        expected.append(e)
    # 业务线合并单元格（第 1、2 条数据）
    ws.merge_cells(start_row=4, start_column=5, end_row=5, end_column=5)
    ws.append(["合计", None, None, None, None, "=SUM(F4:F33)"])
    ws.append(["备注：本表为区域销售报送汇总，请营销管控部核对后导入台账。"])
    for col, w in zip("ABCDEFGHIJ", [6, 14, 28, 14, 14, 16, 18, 8, 22, 16]):
        ws.column_dimensions[col].width = w
    wb.save(OUT / "dirty_contracts.xlsx")
    (OUT / "dirty_contracts_expected.json").write_text(json.dumps(
        {"target": "contract", "header_row": 3, "data_rows": len(expected), "fields": FIELDS,
         "rows": expected}, ensure_ascii=False, indent=1), "utf-8")
    return len(expected)


