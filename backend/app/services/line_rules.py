"""业务线判定：按项目/合同名称关键词归类，命中不了就归「待定」。

规则是有序的，先匹配的先生效；每个关键词只对应一条业务线，避免同一名称被反复解释。
判定结果同时返回命中的关键词，写进备注便于人工复核——「为什么是这条线」必须可追溯。

2026-11-13 与总经办确认：业务线按项目名称关键词判，判不出来的写「待定」，不许猜。
"""
import re

LINES = {"XY": "数字校园", "AF": "综合智慧安防", "KP": "素质教育考评", "YW": "运维服务", "TD": "待定"}

# (业务线, 关键词...)  顺序即优先级：考试/考评类最具体，放最前；泛化的「学校」放最后
RULES: list[tuple[str, tuple[str, ...]]] = [
    ("KP", ("中考", "体考", "体测", "体质", "体育", "英语听说", "听说考试", "考评", "阅卷", "实验操作", "理化生",
            "模拟测", "抽测", "测评", "艺考", "音乐考试", "美术考试", "考场", "考试")),
    ("AF", ("安检", "监控", "视频", "报警", "安防", "门禁", "道闸", "对讲", "广播", "信号覆盖", "无线通信",
            "信号灯", "信号管控", "电警", "卡口", "周界", "巡更", "机房", "服务器", "网络覆盖", "专线", "基站",
            "交通")),
    ("YW", ("运维", "维保", "维护", "维修", "服务费", "技术服务", "技术咨询", "运营服务", "托管", "续费",
            "租赁", "框架协议", "代维", "驻场")),
    ("XY", ("智慧校园", "校园网", "录播", "班班通", "一体机", "食堂", "饭堂", "宿舍", "图书馆", "教室",
            "实验室", "实训", "教学", "教育", "学校", "中学", "小学", "幼儿园", "学生", "教师", "校园",
            "平台建设", "信息化")),
]

_COMPILED = [(code, keywords, re.compile("|".join(map(re.escape, keywords)))) for code, keywords in RULES]


def classify(title: str | None) -> tuple[str, str | None]:
    """返回 (业务线, 命中的关键词)；都没命中返回 ("TD", None)。"""
    text = str(title or "")
    for code, _keywords, pattern in _COMPILED:
        matched = pattern.search(text)
        if matched:
            return code, matched.group(0)
    return "TD", None
