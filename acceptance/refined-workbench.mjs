import assert from 'node:assert/strict'
import { chromium } from 'playwright'
import { API, WEB, OUT, call, loginPage, save, shot, step as record } from './lib.mjs'

const health = await fetch(API + '/health').then(r => r.json())
if (health.env !== 'test' || !['127.0.0.1', 'localhost'].includes(new URL(API).hostname)) throw new Error('Only an isolated local test service is allowed')
const browser = await chromium.launch({ executablePath: process.env.CHROME_BIN || undefined })
const users = (await call('admin','GET','/admin/users',{page_size:100})).items
const user = id => users.find(u=>u.userid===id)
const project = await call('admin','POST','/operations',{name:'细化会议验收 '+Date.now(),owner_id:user('wujun').id})
for(const [name,role] of [['xiekai','member'],['xuhao','member'],['yangyue','viewer']]) await call('admin','POST',`/operations/${project.id}/members`,{user_id:user(name).id,role})
const school = await call('admin','POST',`/operations/${project.id}/schools`,{name:'雅韶中学验收样例'})
await call('admin','PUT',`/operations/${project.id}/schools/${school.id}/region`,{region:'阳东'})
const task = await call('admin','POST',`/operations/${project.id}/tasks`,{title:'我的关键接口任务',owner_id:user('xiekai').id,due_date:'2026-10-25'})
const other = await call('admin','POST',`/operations/${project.id}/tasks`,{title:'其他成员的任务',owner_id:user('xuhao').id,due_date:'2026-10-25'})
const manager = await loginPage(browser,'wujun'), employee = await loginPage(browser,'xiekai',{width:390,height:844})
const url = WEB+'/operations/'+project.id
async function box(scope,name){ await scope.getByRole('combobox',{name,exact:true}).locator('xpath=ancestor::div[contains(@class,"el-select__wrapper")]').click() }
async function step(id,title,fn){await record(id,title,async()=>{try{return await fn()}catch(e){await shot(manager,id+'-manager-failure').catch(()=>{});await shot(employee,id+'-employee-failure').catch(()=>{});throw e}});save()}
const wait = loc => loc.waitFor({state:'visible',timeout:12000})

await step('REF-01','手机首页直接进入自己的项目与任务',async()=>{
  await employee.goto(WEB)
  const panel=employee.getByRole('region',{name:'我的工作入口'}).or(employee.locator('.my-work'))
  await wait(panel.getByRole('link',{name:new RegExp(project.name)}))
  await panel.getByRole('link',{name:new RegExp(project.name)}).click()
  await employee.locator('.task-card').filter({hasText:'我的关键接口任务'}).click()
  await wait(employee.getByRole('dialog',{name:'任务详情'}).getByRole('heading',{name:'我的关键接口任务',exact:true}))
  await employee.getByRole('dialog',{name:'任务详情'}).getByRole('button',{name:'关闭',exact:true}).last().click()
  await employee.goto(WEB)
  await wait(employee.locator('.my-work').getByRole('link',{name:new RegExp(project.name)}))
  assert.ok(await employee.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1))
  return shot(employee,'refined-mobile-home')
})

await step('REF-02','管理者逐人隐藏营收采购并限制到本人相关任务',async()=>{
  await manager.goto(url)
  await manager.getByRole('tab',{name:'项目团队',exact:true}).click()
  await manager.locator('.visibility summary').click()
  const row=manager.locator('.visibility .el-table__row').filter({hasText:user('xiekai').name})
  await row.getByRole('button',{name:'设置可见',exact:true}).click()
  const dialog=manager.getByRole('dialog',{name:user('xiekai').name+' · 本项目可见内容'})
  await dialog.locator('.el-radio').filter({hasText:'仅本人负责、被指定查看或审核的任务'}).click()
  for(const label of ['项目进度','学校采购','每日营收','设备产品','项目团队','经费与审批']) await dialog.locator('.el-checkbox').filter({hasText:new RegExp('^'+label+'$')}).click()
  await dialog.getByRole('button',{name:'保存此人可见范围'}).click()
  await dialog.waitFor({state:'hidden'})
  await employee.goto(url)
  await wait(employee.getByRole('tab',{name:'市场开拓',exact:true}))
  assert.equal(await employee.getByRole('tab',{name:'每日收入',exact:true}).count(),0)
  assert.equal(await employee.getByRole('tab',{name:'学校采购',exact:true}).count(),0)
  assert.equal(await employee.getByText('其他成员的任务',{exact:true}).count(),0)
  const result=await call('xiekai','GET',`/operations/${project.id}`)
  assert.equal(result.financials.total_income,null)
  assert.equal(result.schools[0].incomes,undefined)
  assert.equal((await call('xiekai','GET',`/operations/tasks/${other.id}`,null,{raw:true})).status,404)
  return shot(manager,'refined-member-visibility')
})

